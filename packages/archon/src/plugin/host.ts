import { posix } from 'node:path';
import type { ResolvedConfig } from '../config/types.js';
import type { Diagnostics } from '../diagnostics.js';
import type { IRDocument } from '../ir/types.js';
import { runPluginPasses } from '../passes/index.js';
import { CodeWriter } from '../writer/code-writer.js';
import type { ArchonPlugin, EmittedFile, PluginContext } from './types.js';

type AnyPlugin = ArchonPlugin<any, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

const DEFAULT_HEADER = ['This file was generated by Archon. Do not edit manually.'];

/** プラグインの出力先ディレクトリ（`output.path` 相対、posix 正規化済み、`.` は出力ルート）。 */
export function resolveOutputDir(plugin: AnyPlugin): string {
  const configured = (plugin.options as { output?: unknown } | null)?.output;
  const dir = typeof configured === 'string' && configured !== '' ? configured : plugin.name;
  return posix.normalize(dir.replaceAll('\\', '/')).replace(/\/+$/, '') || '.';
}

/**
 * 全プラグインを依存順に実行して、出力ファイル（`output.path` 相対のパス）を返す。
 * `opts.only` を指定した場合、そのプラグインと推移的な依存だけを実行する。
 * 渡された `ir` は変更しない。
 */
export async function runPlugins(
  ir: IRDocument,
  config: ResolvedConfig,
  diagnostics: Diagnostics,
  opts: { only?: string[] } = {},
): Promise<EmittedFile[]> {
  const registry = collectPlugins(config.plugins, diagnostics);
  const ordered = sortTopologically(registry, diagnostics);
  const selected = opts.only ? selectOnly(registry, opts.only, diagnostics) : undefined;
  const plugins = selected ? ordered.filter((p) => selected.has(p.name)) : ordered;

  const shared = structuredClone(ir);
  for (const plugin of plugins) {
    plugin.definition.transformIR?.(shared, { options: plugin.options, diagnostics });
  }

  const files = new Map<string, EmittedFile>();
  const apis = new Map<string, unknown>();
  const inlineSchemaName = config.parser.hooks?.inlineSchemaName;

  for (const plugin of plugins) {
    const outputDir = resolveOutputDir(plugin);
    const req = plugin.definition.irRequirements?.(plugin.options) ?? {};
    const ctx: PluginContext<unknown> = {
      ir: runPluginPasses(shared, req, inlineSchemaName),
      options: plugin.options,
      config,
      outputDir,
      diagnostics,
      emit(relativePath, content) {
        const path = posix.join(outputDir, relativePath.replaceAll('\\', '/'));
        if (path === '..' || path.startsWith('../') || posix.isAbsolute(path) || isOutside(outputDir, path)) {
          diagnostics.error(
            'invalid-output-path',
            `Plugin "${plugin.name}" tried to emit "${relativePath}", which is outside its output directory.`,
          );
        }
        if (files.has(path)) {
          diagnostics.error('duplicate-output', `Output path "${path}" was emitted more than once (plugin "${plugin.name}").`);
        }
        files.set(path, { path, content });
      },
      headerLines: (language) => config.output.header({ defaultValue: [...DEFAULT_HEADER], language }),
      writer: (writerOpts) => new CodeWriter(writerOpts),
      plugin<API = unknown>(name: string): API {
        if (!apis.has(name)) {
          return diagnostics.error(
            'plugin-not-ready',
            `Plugin "${plugin.name}" requested the API of "${name}", which has not run yet. Declare it in "dependencies".`,
          );
        }
        return apis.get(name) as API;
      },
    };
    apis.set(plugin.name, await plugin.definition.generate(ctx));
  }

  return [...files.values()];
}

/** `outputDir` が `.` 以外のとき、`path` がその配下にあることを確認する。 */
function isOutside(outputDir: string, path: string): boolean {
  return outputDir !== '.' && !path.startsWith(`${outputDir}/`);
}

/** 登録順を保ったまま、未登録の依存を factories から自動追加する。 */
function collectPlugins(initial: AnyPlugin[], diagnostics: Diagnostics): Map<string, AnyPlugin> {
  const registry = new Map<string, AnyPlugin>();
  for (const plugin of initial) {
    if (registry.has(plugin.name)) {
      diagnostics.error('plugin-duplicate', `Plugin "${plugin.name}" is registered more than once.`);
    }
    registry.set(plugin.name, plugin);
  }
  // registry は走査中に伸びる（Map は挿入順に反復される）
  for (const plugin of registry.values()) {
    for (const dep of plugin.definition.dependencies ?? []) {
      if (registry.has(dep)) continue;
      const factory = plugin.definition.factories?.[dep];
      if (!factory) {
        diagnostics.error(
          'plugin-missing-dependency',
          `Plugin "${plugin.name}" depends on "${dep}", which is not registered and has no factory.`,
        );
      }
      registry.set(dep, factory());
    }
  }
  return registry;
}

function sortTopologically(registry: Map<string, AnyPlugin>, diagnostics: Diagnostics): AnyPlugin[] {
  const sorted: AnyPlugin[] = [];
  const state = new Map<string, 'visiting' | 'done'>();

  const visit = (plugin: AnyPlugin, chain: string[]): void => {
    const s = state.get(plugin.name);
    if (s === 'done') return;
    if (s === 'visiting') {
      const cycle = [...chain.slice(chain.indexOf(plugin.name)), plugin.name];
      diagnostics.error('plugin-cycle', `Plugin dependency cycle: ${cycle.join(' -> ')}`);
    }
    state.set(plugin.name, 'visiting');
    for (const dep of plugin.definition.dependencies ?? []) {
      const depPlugin = registry.get(dep);
      if (depPlugin) visit(depPlugin, [...chain, plugin.name]);
    }
    state.set(plugin.name, 'done');
    sorted.push(plugin);
  };

  for (const plugin of registry.values()) visit(plugin, []);
  return sorted;
}

/** `only` に挙がったプラグインと、その推移的な依存の名前集合。 */
function selectOnly(registry: Map<string, AnyPlugin>, only: string[], diagnostics: Diagnostics): Set<string> {
  const selected = new Set<string>();
  const add = (name: string): void => {
    if (selected.has(name)) return;
    const plugin = registry.get(name);
    if (!plugin) {
      diagnostics.error('plugin-unknown', `Unknown plugin "${name}" in "only".`);
      return;
    }
    selected.add(name);
    for (const dep of plugin.definition.dependencies ?? []) add(dep);
  };
  for (const name of only) add(name);
  return selected;
}

import type { PluginContext } from '../../plugin/types.js';
import type { CodeWriter } from '../../writer/code-writer.js';
import type { RubyPluginOptions } from './index.js';

export const GENERATED_MARKER = 'Code generated by Archon. DO NOT EDIT.';

/** The generated header as `#` lines: the marker, then `output.header`. */
export function headerComment(ctx: PluginContext<RubyPluginOptions>): string[] {
  return [GENERATED_MARKER, ...ctx.headerLines('ruby')].flatMap((l) => l.split('\n')).map((l) => (l === '' ? '#' : `# ${l}`));
}

/** A Ruby source file: the frozen string literal comment, the header, then `body` (written by `fn`) inside `module <name>`. */
export function rbFile(ctx: PluginContext<RubyPluginOptions>, moduleName: string | undefined, fn: (w: CodeWriter) => void): string {
  const w = ctx.writer({ indent: '  ' });
  w.line('# frozen_string_literal: true');
  w.blank();
  w.lines(headerComment(ctx));
  w.blank();
  if (moduleName === undefined) fn(w);
  else w.block(`module ${moduleName}`, () => fn(w), 'end');
  return w.toString();
}

/** Comment lines for a doc text: each line trimmed at the end, runs of blank lines collapsed, none at either end. */
export function docLines(text: string | undefined): string[] {
  if (text === undefined) return [];
  const out: string[] = [];
  for (const raw of text.replace(/\r\n?/g, '\n').split('\n')) {
    const line = raw.replace(/\s+$/, '');
    if (line === '' && (out.length === 0 || out[out.length - 1] === '')) continue;
    out.push(line);
  }
  while (out.length > 0 && out[out.length - 1] === '') out.pop();
  return out;
}

/** Writes a doc text as `#` comments (nothing for an empty text). */
export function doc(w: CodeWriter, text: string | undefined): void {
  for (const line of docLines(text)) w.line(line === '' ? '#' : `# ${line}`);
}

/** A Ruby string literal: single-quoted unless it needs escapes only double quotes have. Lone surrogates become U+FFFD. */
export function rbString(value: string): string {
  const clean = [...value].map((ch) => {
    const code = ch.codePointAt(0) as number;
    return code >= 0xd800 && code <= 0xdfff ? '�' : ch;
  });
  if (clean.every((ch) => (ch.codePointAt(0) as number) >= 0x20 && ch !== '\x7f')) {
    return `'${clean.join('').replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  }
  let out = '"';
  for (const ch of clean) {
    const code = ch.codePointAt(0) as number;
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '#') out += '\\#';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20 || code === 0x7f) out += `\\x${code.toString(16).padStart(2, '0').toUpperCase()}`;
    else out += ch;
  }
  return `${out}"`;
}

/** A Ruby symbol literal (`:name`, or `:"x-y"` when it is not a plain identifier). */
export function rbSymbol(name: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*[?!]?$/.test(name) ? `:${name}` : `:${rbString(name)}`;
}

/** Writes `items` one per line as the arguments of `open(` … `)`, each followed by a comma (none when empty). */
export function writeList(w: CodeWriter, open: string, items: string[], close = ')'): void {
  if (items.length === 0) {
    w.line(`${open}${close}`);
    return;
  }
  w.line(open);
  w.indent(() => items.forEach((item) => w.line(`${item},`)));
  w.line(close);
}

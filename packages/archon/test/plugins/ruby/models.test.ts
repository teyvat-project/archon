import { describe, expect, it } from 'vitest';
import { arr, bin, bool, date, dateTime, doc, enumOf, generate, int, model, nullable, num, obj, prop, ref, str, union } from './helpers.js';

const shapes = () =>
  doc({
    Shape: union([ref('Circle'), ref('Square')], { property: 'kind', mapping: { circle: 'Circle', square: 'Square' } }),
    Circle: obj([prop('kind', { kind: 'const', value: 'circle', nullable: false }, true), prop('radius', num, true)]),
    Square: obj([prop('kind', enumOf(['square']), true), prop('side', num, true)]),
  });

describe('ruby plugin: models', () => {
  it('renders Data models with keyword initializers and a JSON field table', async () => {
    const { files } = await generate(
      doc({
        Pet: obj(
          [
            prop('name', { ...str, description: 'The name.\nSecond line.' }, true),
            prop('note', str),
            prop('tags', arr(nullable(str))),
            prop('parentId', nullable(str), true),
            prop('born', date),
            prop('seen', dateTime, true),
            prop('photo', bin),
            prop('blob', { kind: 'string', format: 'byte', nullable: false }),
            prop('extra', { kind: 'unknown', nullable: false }),
            prop('labels', obj([], { additionalProperties: int })),
            prop('old', { ...bool, deprecated: true }),
          ],
          { description: 'A pet.\n\n\n  - indented' },
        ),
      }),
    );
    const pet = model(files, 'pet');
    expect(pet.startsWith('# frozen_string_literal: true\n\n# Code generated by Archon. DO NOT EDIT.\n# Generated header\n\nmodule Api\n')).toBe(true);
    expect(pet).toContain('  # A pet.\n  #\n  #   - indented\n  Pet = ::Data.define(:name, :note, :tags, :parent_id, :born, :seen, :photo, :blob, :extra, :labels, :old)\n');
    expect(pet).toContain('    # @param name [::String] The name.\n    #   Second line.\n');
    expect(pet).toContain('    # @param parent_id [::String, nil]\n');
    expect(pet).toContain('    # @param old [Boolean, nil] Deprecated in the API.\n');
    expect(pet).toContain(
      '    def initialize(name:, note: nil, tags: nil, parent_id:, born: nil, seen:, photo: nil, blob: nil, extra: nil, labels: nil, old: nil)\n      super\n    end',
    );
    expect(pet).toContain(
      [
        '    json_fields(',
        "      Core::Field.new(name: :name, wire: 'name', type: Core::Types::STRING, required: true),",
        "      Core::Field.new(name: :note, wire: 'note', type: Core::Types::STRING),",
        "      Core::Field.new(name: :tags, wire: 'tags', type: Core::Types.array(Core::Types.nullable(Core::Types::STRING))),",
        "      Core::Field.new(name: :parent_id, wire: 'parentId', type: Core::Types::STRING, required: true, nullable: true),",
        "      Core::Field.new(name: :born, wire: 'born', type: Core::Types::DATE),",
        "      Core::Field.new(name: :seen, wire: 'seen', type: Core::Types::TIME, required: true),",
        "      Core::Field.new(name: :photo, wire: 'photo', type: Core::Types::UPLOAD),",
        "      Core::Field.new(name: :blob, wire: 'blob', type: Core::Types::BYTES),",
        "      Core::Field.new(name: :extra, wire: 'extra', type: Core::Types::ANY),",
        "      Core::Field.new(name: :labels, wire: 'labels', type: Core::Types.map(Core::Types::INTEGER)),",
        "      Core::Field.new(name: :old, wire: 'old', type: Core::Types::BOOLEAN),",
        '    )',
      ].join('\n'),
    );
  });

  it('refers to other models lazily, including itself', async () => {
    const { files } = await generate(doc({ Node: obj([prop('children', arr(ref('Node')), true), prop('parent', ref('Node'))]) }));
    const node = model(files, 'node');
    expect(node).toContain("type: Core::Types.array(Core::Types.ref(-> { Node })), required: true),");
    expect(node).toContain("Core::Field.new(name: :parent, wire: 'parent', type: Core::Types.ref(-> { Node })),");
  });

  it('defaults the discriminator of a variant to its tag', async () => {
    const { files } = await generate(shapes());
    expect(model(files, 'circle')).toContain("def initialize(kind: 'circle', radius:)");
    expect(model(files, 'square')).toContain("def initialize(kind: 'square', side:)");
    expect(model(files, 'shape')).toContain(
      [
        '  module Shape',
        '    extend Core::Union',
        '',
        "    # Picks the variant by the discriminator 'kind'; an unknown value is kept as Core::Unknown.",
        "    discriminator 'kind', {",
        "      'circle' => Core::Types.ref(-> { Circle }),",
        "      'square' => Core::Types.ref(-> { Square }),",
        '    }',
        '  end',
      ].join('\n'),
    );
  });

  it('renders untagged unions as ordered variants and flattens unions that refer back to themselves', async () => {
    const { files } = await generate(
      doc({
        Pet: union([ref('Cat'), str, dateTime, { kind: 'null', nullable: false }]),
        Cat: obj([prop('name', str, true)]),
        U1: union([ref('U2'), str]),
        U2: union([ref('U1'), int]),
      }),
    );
    expect(model(files, 'pet')).toContain('    variants(\n      Core::Types.ref(-> { Cat }),\n      Core::Types::STRING,\n      Core::Types::TIME,\n    )');
    expect(model(files, 'u1')).toContain('    variants(\n      Core::Types::INTEGER,\n      Core::Types::STRING,\n    )');
  });

  it('renders enums as modules of constants', async () => {
    const { files } = await generate(
      doc({
        Status: enumOf(['active', 'is-known', '', 'VALUES', 'Active']),
        Level: { kind: 'enum', base: 'integer', values: [-1, 0, 1], nullable: false },
        Ratio: { kind: 'enum', base: 'number', values: [0.5, 1.5], nullable: false },
      }),
    );
    expect(model(files, 'status')).toContain(
      [
        '  module Status',
        "    ACTIVE = 'active'",
        "    IS_KNOWN = 'is-known'",
        "    EMPTY = ''",
        "    VALUES2 = 'VALUES'",
        "    ACTIVE2 = 'Active'",
        '',
        '    # Every value the API declares (other values are kept as they are).',
        '    VALUES = [ACTIVE, IS_KNOWN, EMPTY, VALUES2, ACTIVE2].freeze',
        '',
        '    # Whether `value` is one the API declares.',
        '    def self.known?(value) = VALUES.include?(value)',
        '  end',
      ].join('\n'),
    );
    expect(model(files, 'level')).toContain('    V_MINUS_1 = -1\n    V_0 = 0\n    V_1 = 1\n');
    expect(model(files, 'ratio')).toContain('    V_0_5 = 0.5\n    V_1_5 = 1.5\n');
  });

  it('marks deprecated models and writes strings Ruby reads back as written', async () => {
    const { files } = await generate(
      doc({ Old: obj([prop("it's", str), prop('a"#{b}\\', str)], { deprecated: true, description: 'Old.' }), Plain: obj([prop('x\n', str)]) }),
    );
    const old = model(files, 'old');
    expect(old).toContain('  # Old.\n  #\n  # @deprecated Deprecated in the API.\n  Old = ');
    expect(old).toContain("wire: 'it\\'s'");
    expect(old).toContain("wire: 'a\"#{b}\\\\'");
    expect(model(files, 'plain')).toContain('wire: "x\\n"');
  });
});

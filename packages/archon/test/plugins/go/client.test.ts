import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { GO_VERSION } from '../../../src/plugins/go/project.js';
import { readGoRuntime } from '../../../src/plugins/go/runtime.js';
import { doc, file, generate, obj, operation, prop, response, str } from './helpers.js';

const repoRuntime = fileURLToPath(new URL('../../../../../runtimes/go/src', import.meta.url));
const read = (path: string) => readFileSync(fileURLToPath(new URL(`../../../../../${path}`, import.meta.url)), 'utf8');

function withAuth() {
  return doc({ Options: obj([prop('a', str)]) }, [
    operation('GET /a', 'getA', { group: 'catalyst', responses: [response(204)] }),
    operation('GET /b', 'getB', { group: 'core', responses: [response(204)] }),
    operation('GET /c', 'getC', { group: 'use', responses: [response(204)] }),
  ], {
    info: { title: 'Natsuneko Laboratory API', version: '2026.10.23' },
    servers: [{ url: 'https://{env}.api.test:{port}/v1', variables: { env: { default: 'prod' }, port: { default: '8443' } } }],
    securitySchemes: new Map([
      ['bearerAuth', { kind: 'http-bearer' }],
      ['basic', { kind: 'http-basic' }],
      ['apiKey', { kind: 'apiKey', in: 'query', name: 'api_key' }],
      ['oauth2', { kind: 'oauth2', flows: { clientCredentials: { tokenUrl: '/oauth/token', scopes: {} }, authorizationCode: { refreshUrl: '/oauth/refresh', scopes: {} } } }],
      ['oidc', { kind: 'openIdConnect', url: 'https://id.test/.well-known' }],
      ['digest', { kind: 'http-other', scheme: 'digest' }],
      ['get', { kind: 'http-bearer' }],
    ]),
  });
}

describe('go plugin: client, auth and go.mod', () => {
  it('emits DefaultBaseURL, the client with a field per service, and the scheme table', async () => {
    const { files } = await generate(withAuth(), { packageName: undefined });
    const client = file(files, 'client.go');
    expect(client).toContain('package natsunekolaboratoryapi');
    expect(client).toContain('const DefaultBaseURL = "https://prod.api.test:8443/v1"');
    expect(client).toContain('type ClientOptions = core.Options');
    expect(client).toContain('type Client struct {\n\tclient    *core.Client\n\tCatalyst  *CatalystService\n\tCoreValue *CoreValueService\n\tUseValue  *UseValueService\n}');
    expect(client).toContain('\tif options.BaseURL == "" {\n\t\toptions.BaseURL = DefaultBaseURL\n\t}\n\tc := core.NewClient(options, securitySchemes)');
    expect(client).toContain('\t\tCatalyst:  &CatalystService{client: c},');
    expect(client).toContain('func (c *Client) Use(middleware core.Middleware) *Client {');
    expect(client).toContain('func (c *Client) Core() *core.Client {');
    expect(client).toContain('\t"bearerAuth": {Kind: core.SchemeHTTPBearer},');
    expect(client).toContain('\t"apiKey":     {Kind: core.SchemeAPIKey, In: core.APIKeyInQuery, Name: "api_key"},');
    expect(client).toContain('\t"oauth2":     {Kind: core.SchemeOAuth2, TokenURL: "/oauth/token", RefreshURL: "/oauth/refresh"},');
    expect(client).toContain('\t"oidc":       {Kind: core.SchemeOpenIDConnect},');
    expect(client).not.toContain('digest');
    expect(file(files, 'options_model.go')).toContain('type Options struct');
  });

  it('emits Auth with a typed field per scheme', async () => {
    const auth = file((await generate(withAuth())).files, 'auth.go');
    expect(auth).toContain('\t// BearerAuth is the credential of the security scheme "bearerAuth".\n\tBearerAuth core.TokenProvider\n');
    expect(auth).toContain('\tBasic core.BasicProvider\n');
    expect(auth).toContain('\tApiKey core.TokenProvider\n');
    expect(auth).toContain('\tOauth2 *core.OAuth2\n');
    expect(auth).toContain('\tOidc *core.OAuth2\n');
    expect(auth).toContain('\tGet2 core.TokenProvider\n');
    expect(auth).toContain('func (a *Auth) Get(scheme string) any {\n\tif a == nil {\n\t\treturn nil\n\t}\n\tswitch scheme {');
    expect(auth).toContain('\tcase "oauth2":\n\t\tif a.Oauth2 != nil {\n\t\t\treturn a.Oauth2\n\t\t}');
  });

  it('emits go.mod with the module and requirements, or none for package false', async () => {
    const { files } = await generate(withAuth(), { module: 'github.com/acme/api', package: { dependencies: ['github.com/google/uuid v1.6.0'] } });
    expect(file(files, 'go.mod')).toBe(
      `// Code generated by Archon. DO NOT EDIT.\n// Generated header\n\nmodule github.com/acme/api\n\ngo ${GO_VERSION}\n\nrequire (\n\tgithub.com/google/uuid v1.6.0\n)\n`,
    );
    expect(file(files, 'client.go')).toContain('"github.com/acme/api/core"');
    expect((await generate(withAuth(), { package: false })).files.has('go.mod')).toBe(false);
  });

  it('copies the runtime under core without its tests', async () => {
    const { files } = await generate(withAuth());
    const core = [...files.keys()].filter((p) => p.startsWith('core/')).sort();
    const expected = readdirSync(repoRuntime).filter((f) => f.endsWith('.go') && !f.endsWith('_test.go')).sort();
    expect(core).toEqual(expected.map((f) => `core/${f}`));
    expect(readGoRuntime(repoRuntime).map((f) => f.name)).toEqual(expected);
    const client = file(files, 'core/client.go');
    expect(client.startsWith('// Code generated by Archon. DO NOT EDIT.\n// Generated header\n\npackage core\n')).toBe(true);
  });

  it('keeps the Go version of the runtime and e2e modules in step', () => {
    expect(read('runtimes/go/go.mod')).toContain(`\ngo ${GO_VERSION}\n`);
    expect(read('e2e/go/go.mod')).toContain(`\ngo ${GO_VERSION}\n`);
  });
});

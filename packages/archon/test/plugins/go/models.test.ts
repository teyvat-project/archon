import { describe, expect, it } from 'vitest';
import type { IRSchema } from '../../../src/ir/types.js';
import { arr, bin, bool, date, dateTime, doc, enumOf, generate, int, model, nullable, num, obj, prop, ref, str, union } from './helpers.js';

const shapes = () =>
  doc({
    Shape: union([ref('Circle'), ref('Square')], { property: 'kind', mapping: { circle: 'Circle', square: 'Square' } }),
    Circle: obj([prop('kind', { kind: 'const', value: 'circle', nullable: false }, true), prop('radius', num, true)]),
    Square: obj([prop('kind', enumOf(['square']), true), prop('side', num, true)]),
  });

describe('go plugin: models', () => {
  it('renders structs with json tags, pointers for optional values and required checks', async () => {
    const { files } = await generate(
      doc({
        Pet: obj(
          [
            prop('name', str, true),
            prop('note', str),
            prop('tags', arr(str)),
            prop('parentId', nullable(str), true),
            prop('born', date),
            prop('seen', dateTime, true),
            prop('photo', bin),
            prop('extra', { kind: 'unknown', nullable: false }),
            prop('labels', obj([], { additionalProperties: nullable(str) })),
          ],
          { description: 'A pet.\n\n  - indented' },
        ),
      }),
    );
    const pet = model(files, 'pet');
    expect(pet.startsWith('// Code generated by Archon. DO NOT EDIT.\n// Generated header\n\npackage api\n')).toBe(true);
    expect(pet).toContain('import (\n\t"encoding/json"\n\t"time"\n\n\t"api/core"\n)');
    expect(pet).toContain('// A pet.\n//\n// - indented\ntype Pet struct {');
    expect(pet).toContain(
      [
        '\tName     string             `json:"name"`',
        '\tNote     *string            `json:"note,omitempty"`',
        '\tTags     []string           `json:"tags,omitempty"`',
        '\tParentId *string            `json:"parentId"`',
        '\tBorn     *core.Date         `json:"born,omitempty"`',
        '\tSeen     time.Time          `json:"seen"`',
        '\tPhoto    *core.File         `json:"photo,omitempty"`',
        '\tExtra    json.RawMessage    `json:"extra,omitempty"`',
        '\tLabels   map[string]*string `json:"labels,omitempty"`',
      ].join('\n'),
    );
    expect(pet).toContain('func (v *Pet) UnmarshalJSON(data []byte) error {');
    expect(pet).toContain('if err := core.CheckRequired(data, "Pet", []string{"name", "seen"}, []string{"parentId"}); err != nil {');
    expect(pet).toContain('type plain Pet\n\treturn json.Unmarshal(data, (*plain)(v))');
  });

  it('leaves objects without required properties to encoding/json', async () => {
    const { files } = await generate(doc({ Nested: obj([prop('flag', bool)]) }));
    expect(model(files, 'nested')).not.toContain('UnmarshalJSON');
    expect(model(files, 'nested')).not.toContain('"api/core"');
  });

  it('refers to itself through slices and breaks cycles of required value fields with a pointer', async () => {
    const { files } = await generate(
      doc({
        Node: obj([prop('children', arr(ref('Node')), true), prop('parent', ref('Node'))]),
        A: obj([prop('b', ref('B'), true)]),
        B: obj([prop('a', ref('A'), true), prop('c', ref('C'), true)]),
        C: obj([prop('x', str)]),
      }),
    );
    expect(model(files, 'node')).toContain('Children []Node `json:"children"`');
    expect(model(files, 'node')).toContain('Parent   *Node  `json:"parent,omitempty"`');
    expect(model(files, 'a')).toContain('B *B `json:"b"`');
    expect(model(files, 'b')).toContain('A A `json:"a"`');
    expect(model(files, 'b')).toContain('C C `json:"c"`');
  });

  it('renders enums as named types with constants and IsKnown', async () => {
    const { files } = await generate(
      doc({ Status: enumOf(['active', 'in-active', '', 'IsKnown']), Priority: enumOf([1, -1], 'integer'), Ratio: enumOf([0.5, 2], 'number') }),
    );
    const status = model(files, 'status');
    expect(status).toContain('type Status string');
    expect(status).toContain(
      [
        'const (',
        '\tStatusActive   Status = "active"',
        '\tStatusInActive Status = "in-active"',
        '\tStatusEmpty    Status = ""',
        '\tStatusIsKnown  Status = "IsKnown"',
        ')',
      ].join('\n'),
    );
    expect(status).toContain('func (v Status) IsKnown() bool {\n\tswitch v {\n\tcase StatusActive, StatusInActive, StatusEmpty, StatusIsKnown:\n\t\treturn true\n\t}\n\treturn false\n}');
    const priority = model(files, 'priority');
    expect(priority).toContain('type Priority int64');
    expect(priority).toContain('Priority1      Priority = 1');
    expect(priority).toContain('PriorityMinus1 Priority = -1');
    expect(model(files, 'ratio')).toContain('Ratio0_5 Ratio = 0.5');
  });

  it('renders a discriminated union and fills in the tag of its variants', async () => {
    const { files } = await generate(shapes());
    const shape = model(files, 'shape');
    expect(shape).toContain('type Shape struct {\n\tCircle *Circle\n\tSquare *Square\n\t// Raw is the JSON of a value no variant matched; it is written back as is.\n\tRaw json.RawMessage\n}');
    expect(shape).toContain('switch core.Discriminator(data, "kind") {\n\tcase "circle":\n\t\treturn json.Unmarshal(data, &u.Circle)');
    expect(shape).toContain('u.Raw = append(json.RawMessage(nil), data...)');
    expect(shape).toContain('case u.Raw != nil:\n\t\treturn u.Raw, nil');

    const circle = model(files, 'circle');
    expect(circle).toContain('func (v Circle) MarshalJSON() ([]byte, error) {\n\ttype plain Circle\n\tif v.Kind == "" {\n\t\tv.Kind = "circle"\n\t}\n\treturn json.Marshal(plain(v))\n}');
    expect(model(files, 'square')).toContain('if v.Kind == "" {\n\t\tv.Kind = "square"\n\t}');
  });

  it('tries the variants of an untagged union in order, guarded by the JSON type', async () => {
    const ir = doc({
      Pet: union([ref('Cat'), str, arr(ref('Cat')), obj([], { additionalProperties: int }), int, ref('Shape')]),
      Cat: obj([prop('meows', bool, true)]),
      ...Object.fromEntries(shapes().schemas),
    });
    const { files } = await generate(ir);
    const pet = model(files, 'pet');
    expect(pet).toContain('\tCat     *Cat\n\tString  *string\n\tCatList *[]Cat\n\tIntMap  *map[string]int\n\tInt     *int\n\tShape   *Shape\n');
    const order = ['core.Try[Cat]', 'core.Try[string]', 'core.Try[[]Cat]', 'core.Try[map[string]int]', 'core.Try[int]', 'core.Try[Shape]'].map((s) => pet.indexOf(s));
    expect(order.every((i, n) => i > (order[n - 1] ?? -1))).toBe(true);
    expect(pet).toContain('kind := core.JSONType(data)');
    expect(pet).toContain('if kind == "string" {\n\t\tif v, ok := core.Try[string](data); ok {\n\t\t\tu.String = v\n\t\t\treturn nil\n\t\t}\n\t}');
    // A discriminated union only reads objects.
    expect(pet).toContain('if kind == "object" {\n\t\tif v, ok := core.Try[Shape](data); ok {');
  });

  it('flattens untagged unions that refer to each other', async () => {
    const { files } = await generate(doc({ U1: union([ref('U2'), str]), U2: union([ref('U1'), int]) }));
    const u1 = model(files, 'u1');
    expect(u1).not.toContain('core.Try[U2]');
    expect(u1).toContain('core.Try[int]');
    expect(u1).toContain('core.Try[string]');
  });

  it('marks deprecated schemas and fields and warns about unsupported tag names', async () => {
    const { files, diagnostics } = await generate(
      doc({ Old: obj([prop('a', { ...str, deprecated: true, description: 'Old field.' }), prop('a,b', str)], { deprecated: true }) }),
    );
    const old = model(files, 'old');
    expect(old).toContain('// Deprecated: Deprecated in the API.\ntype Old struct {');
    expect(old).toContain('\t// Old field.\n\t//\n\t// Deprecated: Deprecated in the API.\n\tA  *string `json:"a,omitempty"`');
    expect(old).toContain('AB *string `json:"-"`');
    expect(diagnostics.entries.map((d) => d.code)).toContain('unsupported-property-name');
  });

  it('applies typeMappings with imports and typeOverride', async () => {
    const uuid: IRSchema = { kind: 'string', format: 'uuid', nullable: false };
    const { files } = await generate(doc({ Thing: obj([prop('id', uuid, true), prop('n', int)]) }), {
      typeMappings: { 'string:uuid': { type: 'uuid.UUID', import: 'github.com/google/uuid' }, integer: 'int64' },
      hooks: { typeOverride: (s) => (s.kind === 'integer' ? '*big.Int' : undefined) },
    });
    const thing = model(files, 'thing');
    expect(thing).toContain('"github.com/google/uuid"');
    expect(thing).toContain('Id uuid.UUID `json:"id"`');
    expect(thing).toContain('N  *big.Int  `json:"n,omitempty"`');
  });
});
